def main():
    build = os.path.join(root, "build")
    os.makedirs(build, exist_ok=True)
    inc = ["; GENERATED by tools/gen_mstrings.py\n"]
    z = ["; GENERATED by tools/gen_mstrings.py\nmstr_es:\n"]
    for i, (n, es, en) in enumerate(S):
        inc.append("MS_%-10s .equ %d\n" % (n, i * 2))
        z.append("    .dw ms_es_%d\n" % i)
    z.append("mstr_en:\n")
    for i, _ in enumerate(S):
        z.append("    .dw ms_en_%d\n" % i)
    for i, (n, es, en) in enumerate(S):
        z.append('ms_es_%d: .db "%s",0\n' % (i, clean(es).replace('"', "'")))
        z.append('ms_en_%d: .db "%s",0\n' % (i, clean(en).replace('"', "'")))
    open(os.path.join(build, "mstrings.inc"), "w").write("".join(inc))
    open(os.path.join(build, "mstrings.z80"), "w").write("".join(z))


if __name__ == "__main__":
    main()
