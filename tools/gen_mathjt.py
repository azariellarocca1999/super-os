#!/usr/bin/env python3
"""Generate the jump-table equates of the banked pages:
  build/mathjt.inc  from z80-os/math/page3.z80  (calculator, grapher, CAS, converter ...)
  build/p4jt.inc    from z80-os/apps/page4.z80  (periodic table, constants, Wikipedia, weather)"""
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def gen(src_path, start, end, dst, width):
    src = open(os.path.join(root, *src_path)).read()
    a = src.index(start)
    b = src.index(end)
    out = ["; GENERATED by tools/gen_mathjt.py\n"]
    addr = 0x4000
    for line in src[a:b].splitlines():
        m = re.match(r"\s+jp (\w+)\s*;\s*\$([0-9A-F]{4})", line)
        if m:
            assert int(m.group(2), 16) == addr, (m.group(1), hex(addr))
            out.append("%-*s .equ $%04X\n" % (width, m.group(1).upper(), addr))
            addr += 3
    os.makedirs(os.path.join(root, "build"), exist_ok=True)
    open(os.path.join(root, "build", dst), "w").write("".join(out))


gen(("z80-os", "math", "page3.z80"), "M_JT:", "M_JT_END:", "mathjt.inc", 14)
gen(("z80-os", "apps", "page4.z80"), "P4_JT:", "P4_JT_END:", "p4jt.inc", 16)
gen(("z80-os", "games", "page5.z80"), "P5_JT:", "P5_JT_END:", "p5jt.inc", 16)   # also GAME_SOKOBAN / GAME_REVERSI
