#!/usr/bin/env python3
"""Generate z80-os/kernel/sys.inc from the syscall table in kernel/page0.z80."""
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "z80-os", "kernel", "page0.z80")).read()
a = src.index('.fill $0100-$,$FF')
b = src.index('.fill $0200-$,$FF')
ALIAS = {"ui_begin", "ui_line_y", "ui_cols", "ui_wait_any", "inflate_reply", "text_edit", "viewer", "call_pagex"}
addr = 0x100
out = ["; Super-OS syscall table (page 0, fixed addresses) -- GENERATED by tools/gen_sys.py, do not edit\n"]
for line in src[a:b].splitlines():
    m = re.match(r"\s+jp (\w+)\s*;\s*\$([0-9A-F]{4})(.*)", line)
    if m:
        assert int(m.group(2), 16) == addr, (m.group(1), hex(addr))
        out.append("S_%-10s .equ $%04X\n" % (m.group(1).upper(), addr))
        if m.group(1) in ALIAS:
            out.append("%-14s .equ $%04X" % (m.group(1), addr) + chr(10))
        addr += 3
open(os.path.join(root, "z80-os", "kernel", "sys.inc"), "w").write("".join(out))
print(len(out) - 1, "syscalls")
