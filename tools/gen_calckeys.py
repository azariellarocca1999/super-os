#!/usr/bin/env python3
"""Generate build/calckeys.inc: key -> (normal, 2nd, alpha) table, token names and control codes for the math apps."""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(root, "tools"))
import fxlib as F

CTRL = ["NONE", "ENTER", "DEL", "CLEAR", "LEFT", "RIGHT", "UP", "DOWN", "ALPHA", "2ND", "MODE", "MATH", "STO", "QUIT", "YEQ", "GRAPH",
        "VARS", "SQUARE", "INV", "TRACE", "ZOOM", "WINDOW", "STAT"]
KC = {n: i for i, n in enumerate(CTRL)}


def t(name):
    return F.TOKEN_CODE[name]


PI, ANS, EC, EE = 0xF0, 0xF1, 0xF2, 0xF3
# key code: (normal, 2nd, alpha)   (codes from z80-os/kernel/superos.inc)
K = {
    1: ("DOWN", "DOWN", "DOWN"), 2: ("LEFT", "LEFT", "LEFT"), 3: ("RIGHT", "RIGHT", "RIGHT"), 4: ("UP", "UP", "UP"),
    9: ("ENTER", "UP", "ENTER"),
    10: ("+", None, "="), 11: ("-", None, "W"), 12: ("*", None, "R"), 13: ("/", EC, "M"), 14: ("^", PI, "H"),
    15: ("CLEAR", "CLEAR", "CLEAR"),
    17: ("-", ANS, None), 18: ("3", None, None), 19: ("6", None, "V"), 20: ("9", None, "Q"), 21: (")", "]", "L"),
    22: (t("tan"), t("atan"), "G"), 23: ("VARS", None, None),
    25: (".", None, ":"), 26: ("2", None, "Z"), 27: ("5", None, "U"), 28: ("8", None, "P"), 29: ("(", "[", "K"),
    30: (t("cos"), t("acos"), "F"), 31: (None, None, "C"), 32: ("STAT", None, None),
    33: ("0", None, " "), 34: ("1", None, "Y"), 35: ("4", None, "T"), 36: ("7", None, "O"), 37: (",", EE, "J"),
    38: (t("sin"), t("asin"), "E"), 39: (None, None, "B"), 40: ("X", None, "X"),
    42: ("STO", None, "X"), 43: (t("ln"), t("exp"), "S"), 44: (t("log"), t("10^"), "N"),
    45: ("SQUARE", t("sqrt"), "I"), 46: ("INV", None, "D"), 47: ("MATH", None, "A"),
    48: ("ALPHA", "ALPHA", "ALPHA"), 49: ("GRAPH", "GRAPH", "GRAPH"), 50: ("TRACE", "TRACE", "TRACE"), 51: ("ZOOM", "ZOOM", "ZOOM"),
    52: ("WINDOW", "WINDOW", "WINDOW"), 53: ("YEQ", "YEQ", "YEQ"), 54: ("2ND", "2ND", "2ND"), 55: ("MODE", "QUIT", "MODE"),
    56: ("DEL", "DEL", "DEL"),
}


def enc(v):
    if v is None:
        return 0
    if isinstance(v, int):
        return v
    if v in KC:
        return KC[v]
    assert len(v) == 1, v
    return ord(v)


out = ["; GENERATED by tools/gen_calckeys.py\n"]
for n, i in KC.items():
    out.append("KC_%-8s .equ %d\n" % (n, i))
out.append("calc_keytab:                    ; 3 bytes per key code 0..56: normal, 2nd, alpha\n")
for code in range(0, 57):
    row = K.get(code, (None, None, None))
    out.append("    .db %d,%d,%d\n" % tuple(enc(v) for v in row))
out.append("tok_names:\n")
for i in range(len(F.TOKENS)):
    out.append("    .dw tn_%d\n" % i)
for i, n in enumerate(F.TOKENS):
    nm = n.upper() + "("
    out.append('tn_%d: .db "%s",0\n' % (i, nm))
out.append('tn_pi: .db "PI",0\ntn_ans: .db "ANS",0\ntn_e: .db "_E",0\ntn_ee: .db "E",0\n')
# text -> token table, longest names first: .db len,"name",token   (used to read formulas typed by the AI / CAS results)
out.append("txt_names:\n")
for n in sorted(F.TOKENS, key=lambda t: (-len(t), t)):
    if n == "10^":
        continue
    out.append('    .db %d,"%s",%d\n' % (len(n), n.lower(), F.TOKEN_CODE[n]))
out.append("    .db 0\n")
open(os.path.join(root, "build", "calckeys.inc"), "w").write("".join(out))
