#!/usr/bin/env python3
"""Generate build/units.inc: unit conversion tables for the converter app (flash page 3).
Every unit = 8-byte name + factor + offset (6-byte floats):  base = value * factor + offset ."""
import os
import sys
from fractions import Fraction as Fr

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(root, "tools"))
import fxlib as F

CATS = [
    ("LENGTH", [("MM", Fr(1, 1000)), ("CM", Fr(1, 100)), ("M", 1), ("KM", 1000), ("IN", Fr(254, 10000)), ("FT", Fr(3048, 10000)), ("YD", Fr(9144, 10000)),
                ("MI", Fr(1609344, 1000)), ("NMI", 1852), ("UM", Fr(1, 10 ** 6))]),
    ("MASS", [("MG", Fr(1, 10 ** 6)), ("G", Fr(1, 1000)), ("KG", 1), ("T", 1000), ("OZ", Fr(28349523125, 10 ** 12)), ("LB", Fr(45359237, 10 ** 8)), ("ST", Fr(635029318, 10 ** 8))]),
    ("TIME", [("MS", Fr(1, 1000)), ("S", 1), ("MIN", 60), ("H", 3600), ("DAY", 86400), ("WEEK", 604800), ("YEAR", 31557600)]),
    ("TEMP", [("C", 1, Fr(27315, 100)), ("F", Fr(5, 9), Fr(45967, 180)), ("K", 1, 0), ("R", Fr(5, 9), 0)]),
    ("AREA", [("MM2", Fr(1, 10 ** 6)), ("CM2", Fr(1, 10000)), ("M2", 1), ("HA", 10000), ("KM2", 10 ** 6), ("IN2", Fr(64516, 10 ** 8)), ("FT2", Fr(9290304, 10 ** 8)),
              ("ACRE", Fr(40468564224, 10 ** 7))]),
    ("VOLUME", [("ML", Fr(1, 1000)), ("L", 1), ("M3", 1000), ("GAL", Fr(3785411784, 10 ** 9)), ("QT", Fr(946352946, 10 ** 9)), ("PT", Fr(473176473, 10 ** 9)),
                ("CUP", Fr(2365882365, 10 ** 10)), ("FLOZ", Fr(2957352956, 10 ** 11)), ("IN3", Fr(16387064, 10 ** 9))]),
    ("SPEED", [("M/S", 1), ("KM/H", Fr(10, 36)), ("MPH", Fr(44704, 100000)), ("KN", Fr(1852, 3600)), ("FT/S", Fr(3048, 10000))]),
    ("ENERGY", [("J", 1), ("KJ", 1000), ("CAL", Fr(4184, 1000)), ("KCAL", 4184), ("WH", 3600), ("KWH", 3600000), ("EV", Fr(1602176634, 10 ** 28)), ("BTU", Fr(105505585262, 10 ** 8))]),
    ("PRESS", [("PA", 1), ("KPA", 1000), ("BAR", 100000), ("ATM", 101325), ("PSI", Fr(689475729, 100000)), ("MMHG", Fr(133322387, 1000000)), ("TORR", Fr(101325, 760))]),
    ("POWER", [("W", 1), ("KW", 1000), ("MW", 10 ** 6), ("HP", Fr(7456998716, 10 ** 7)), ("BTU/H", Fr(2930711, 10 ** 7))]),
    ("DATA", [("BIT", Fr(1, 8)), ("B", 1), ("KB", 1000), ("MB", 10 ** 6), ("GB", 10 ** 9), ("TB", 10 ** 12), ("KIB", 1024), ("MIB", 1048576), ("GIB", 1073741824)]),
    ("ANGLE", [("RAD", 1), ("DEG", F.PI / 180), ("GRAD", F.PI / 200), ("TURN", 2 * F.PI), ("ARCMIN", F.PI / 10800)]),
]
out = ["; GENERATED by tools/gen_units.py -- converter unit tables\n"]
out.append("cv_cats:\n")
for i, (n, us) in enumerate(CATS):
    out.append("    .dw cv_units_%d\n    .db %d,%d\n" % (i, len(us), 0))
for i, (n, us) in enumerate(CATS):
    out.append("cv_units_%d:\n" % i)
    for u in us:
        name = u[0]
        f = Fr(u[1]) if not isinstance(u[1], Fr) else u[1]
        o = Fr(u[2]) if len(u) > 2 else Fr(0)
        out.append('    .db "%s"\n    .fill %d,0\n    %s\n    %s\n' % (name, 8 - len(name), F.db(F.pack(f)), F.db(F.pack(o))))
open(os.path.join(root, "build", "units.inc"), "w").write("".join(out))
print(sum(len(u) for _, u in CATS), "units")
