#!/usr/bin/env python3
"""Games build step: assemble games/chip8/*.c8 -> build/pagex06.bin (flash page 6: directory + ROMs) and build/c8keys.inc
(calculator key -> CHIP-8 key table).  Pack 0 = ARCADE, pack 1 = ACTION."""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(root, "tools"))
import chip8  # noqa: E402

GAMES = [("PONG", 0, "pong"), ("BREAKOUT", 0, "breakout"), ("SNAKE", 0, "snake"),
         ("INVADERS", 1, "invaders"), ("DODGE", 1, "dodge"), ("SIMON", 1, "simon")]

# calculator key code -> CHIP-8 key (number pad mirrors the CHIP-8 keypad layout, arrows are the d-pad on 2/4/6/8, ENTER and 2ND = 5)
KEYMAP = {36: 1, 28: 2, 20: 3, 13: 12, 35: 4, 27: 5, 19: 6, 12: 13, 34: 7, 26: 8, 18: 9, 11: 14, 33: 10, 25: 0, 17: 11, 10: 15,
          4: 2, 1: 8, 2: 4, 3: 6, 9: 5, 54: 5}


def build():
    out = os.path.join(root, "build")
    os.makedirs(out, exist_ok=True)
    roms = []
    for name, pack, f in GAMES:
        roms.append(chip8.assemble(open(os.path.join(root, "games", "chip8", f + ".c8")).read(), f))
    head = 1 + 12 * 16
    page = bytearray([len(GAMES)])
    data = bytearray()
    for (name, pack, f), rom in zip(GAMES, roms):
        off = 0x4000 + head + len(data)
        page += name.encode().ljust(10, b"\0") + bytes([pack, 0, off & 255, off >> 8, len(rom) & 255, len(rom) >> 8])
        data += rom
    page = page.ljust(head, b"\0") + data
    assert len(page) <= 16384
    open(os.path.join(out, "pagex06.bin"), "wb").write(page)
    lines = ["; GENERATED by tools/gen_c8.py: row, mask, chip key\nc8_keytab:\n"]
    for code, ck in sorted(KEYMAP.items()):
        lines.append("    .db %d,%d,%d\n" % ((code - 1) >> 3, 1 << ((code - 1) & 7), ck))
    lines.append("    .db $FF\n")
    open(os.path.join(out, "c8keys.inc"), "w").write("".join(lines))
    tab = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = ((c << 1) ^ 0x07) & 255 if c & 0x80 else (c << 1) & 255
        tab.append(c)
    with open(os.path.join(out, "crc8tab.inc"), "w") as f:
        f.write("; GENERATED by tools/gen_c8.py: CRC-8 poly $07\ncrc8tab:\n")
        for i in range(0, 256, 16):
            f.write("    .db " + ",".join(str(x) for x in tab[i:i + 16]) + "\n")
    return roms


if __name__ == "__main__":
    r = build()
    print("games:", [(g[0], len(x)) for g, x in zip(GAMES, r)])
