#!/usr/bin/env python3
"""Generate the periodic table data for flash page 4.
Needs the `mendeleev` package once (pip install --target build/pydeps mendeleev); the result is cached in tools/ptable_data.txt
so a normal build does not need it.
Writes build/ptable.zx0 (ZX0 stream of the text records) and build/ptgrid.inc (18 x 9 grid of atomic numbers)."""
import os
import subprocess
import sys
import unicodedata

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(root, "tools", "ptable_data.txt")

ES = ("Hidrogeno Helio Litio Berilio Boro Carbono Nitrogeno Oxigeno Fluor Neon Sodio Magnesio Aluminio Silicio Fosforo Azufre Cloro Argon Potasio Calcio "
      "Escandio Titanio Vanadio Cromo Manganeso Hierro Cobalto Niquel Cobre Zinc Galio Germanio Arsenico Selenio Bromo Kripton Rubidio Estroncio Itrio "
      "Circonio Niobio Molibdeno Tecnecio Rutenio Rodio Paladio Plata Cadmio Indio Estano Antimonio Telurio Yodo Xenon Cesio Bario Lantano Cerio "
      "Praseodimio Neodimio Prometio Samario Europio Gadolinio Terbio Disprosio Holmio Erbio Tulio Iterbio Lutecio Hafnio Tantalo Wolframio Renio Osmio "
      "Iridio Platino Oro Mercurio Talio Plomo Bismuto Polonio Astato Radon Francio Radio Actinio Torio Protactinio Uranio Neptunio Plutonio Americio "
      "Curio Berkelio Californio Einstenio Fermio Mendelevio Nobelio Lawrencio Rutherfordio Dubnio Seaborgio Bohrio Hasio Meitnerio Darmstadtio "
      "Roentgenio Copernicio Nihonio Flerovio Moscovio Livermorio Teneso Oganeson").split()

CATS = {0: {3, 11, 19, 37, 55, 87}, 1: {4, 12, 20, 38, 56, 88}, 3: {13, 31, 49, 50, 81, 82, 83, 84, 113, 114, 115, 116},
        4: {5, 14, 32, 33, 51, 52}, 5: {1, 6, 7, 8, 15, 16, 34}, 6: {9, 17, 35, 53, 85, 117}, 7: {2, 10, 18, 36, 54, 86, 118}}


def category(z):
    for c, zs in CATS.items():
        if z in zs:
            return c
    if 57 <= z <= 71:
        return 8
    if 89 <= z <= 103:
        return 9
    return 2


def ascii_(t):
    return unicodedata.normalize("NFKD", t).encode("ascii", "ignore").decode()


def num(v, fmt="%.4g"):
    if v is None:
        return ""
    s = fmt % v
    return s


def build_cache():
    sys.path.insert(0, os.path.join(root, "build", "pydeps"))
    from mendeleev import element
    lines = []
    for z in range(1, 119):
        e = element(z)
        mass = ("%.3f" % e.atomic_weight).rstrip("0").rstrip(".")
        mp = "" if e.melting_point is None else "%d" % round(e.melting_point)
        bp = "" if e.boiling_point is None else "%d" % round(e.boiling_point)
        en = "" if e.en_pauling is None else "%.2f" % e.en_pauling
        dens = "" if e.density is None else ("%.4g" % e.density)
        group = "" if (57 <= z <= 71 or 89 <= z <= 103) else str(e.group_id or "")
        cfg = ascii_(e.econf).replace("\n", " ")
        lines.append("|".join([e.symbol, ascii_(e.name), ES[z - 1], mass, group, str(e.period), str(category(z)), cfg, mp, bp, en, dens]))
    open(CACHE, "w").write("\n".join(lines) + "\n")


def main():
    if not os.path.exists(CACHE):
        build_cache()
    text = open(CACHE).read()
    lines = text.strip().split("\n")
    assert len(lines) == 118
    os.makedirs(os.path.join(root, "build"), exist_ok=True)
    src = os.path.join(root, "build", "ptable.txt")
    open(src, "w", newline="\n").write(text)
    dst = os.path.join(root, "build", "ptable.zx0")
    subprocess.run([os.path.join(root, "tools", "bin", "zx0.exe"), "-f", src, dst], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    # grid 18 columns x 9 rows of atomic numbers
    grid = [[0] * 18 for _ in range(9)]
    for z, ln in enumerate(lines, start=1):
        f = ln.split("|")
        group, period = f[4], int(f[5])
        if 57 <= z <= 71:
            grid[7][2 + z - 57] = z
        elif 89 <= z <= 103:
            grid[8][2 + z - 89] = z
        else:
            grid[period - 1][int(group) - 1] = z
    out = ["; GENERATED by tools/gen_ptable.py\npt_grid:\n"]
    for r in grid:
        out.append("    .db %s\n" % ",".join(str(v) for v in r))
    open(os.path.join(root, "build", "ptgrid.inc"), "w").write("".join(out))
    print("periodic table: %d bytes text -> %d bytes zx0" % (len(text), os.path.getsize(dst)))


if __name__ == "__main__":
    main()
