def pack(table, rows):
    out = bytearray()
    for code in range(32, 96):
        glyph = table[chr(code)]
        assert len(glyph) == rows, chr(code)
        for r in glyph:
            v = 0
            for i, ch in enumerate(r):
                if ch == '#':
                    v |= 0x80 >> i
            out.append(v)
    return bytes(out)


def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    f3, f5 = pack(G3, 5), pack(G5, 7)
    assert len(f3) == 320 and len(f5) == 448
    open(os.path.join(outdir, "font3.bin"), "wb").write(f3)
    open(os.path.join(outdir, "font5.bin"), "wb").write(f5)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/assets")
