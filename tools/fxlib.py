#!/usr/bin/env python3
"""Reference model of the Z80 float format (6 bytes: exp, sign, 4 mantissa bytes MSB first), the constant tables and the expression tokens."""
import math
from fractions import Fraction


def pack(x):
    """float / Fraction -> 6 bytes (round to nearest 32-bit mantissa)"""
    if x == 0:
        return bytes(6)
    x = Fraction(x)
    s = 1 if x < 0 else 0
    x = abs(x)
    e = 0
    while x >= 1:
        x /= 2
        e += 1
    while x < Fraction(1, 2):
        x *= 2
        e -= 1
    m = round(x * (1 << 32))
    if m >= 1 << 32:
        m >>= 1
        e += 1
    exp = e + 128
    if exp <= 0:
        return bytes(6)
    if exp > 255:
        raise OverflowError(x)
    return bytes([exp, s]) + m.to_bytes(4, "big")


def unpack(b):
    if b[0] == 0:
        return 0.0
    m = int.from_bytes(bytes(b[2:6]), "big")
    v = m / float(1 << 32) * 2.0 ** (b[0] - 128)
    return -v if b[1] else v


def db(b):
    return ".db " + ",".join("$%02X" % c for c in b)


def hi24(x, bits=24):
    """x truncated to `bits` significant bits (Cody-Waite high part)"""
    x = Fraction(x)
    s = 1 if x < 0 else 0
    ax = abs(x)
    e = 0
    while ax >= 1:
        ax /= 2
        e += 1
    while ax < Fraction(1, 2):
        ax *= 2
        e -= 1
    m = int(ax * (1 << bits))
    v = Fraction(m, 1 << bits) * Fraction(2) ** e
    return -v if s else v


# high precision constants as exact rationals via decimal strings
def D(s):
    from decimal import Decimal
    return Fraction(Decimal(s))


PI = D("3.14159265358979323846264338327950288")
LN2 = D("0.693147180559945309417232121458176568")
LN10 = D("2.30258509299404568401799145468436421")
E = D("2.71828182845904523536028747135266250")


def coeffs_exp():
    return [Fraction(1, math.factorial(n)) for n in range(12, -1, -1)]


def coeffs_sin():           # sin r = r * P(r^2),  highest degree first
    return [Fraction((-1) ** n, math.factorial(2 * n + 1)) for n in range(7, -1, -1)]


def coeffs_cos():
    return [Fraction((-1) ** n, math.factorial(2 * n)) for n in range(7, -1, -1)]


def coeffs_atan():          # atan x = x * P(x^2)
    return [Fraction((-1) ** n, 2 * n + 1) for n in range(8, -1, -1)]


def coeffs_atanh():         # atanh s = s * P(s^2)
    return [Fraction(1, 2 * n + 1) for n in range(9, -1, -1)]


SCALAR = {
    "one": Fraction(1), "two": Fraction(2), "half": Fraction(1, 2), "ten": Fraction(10), "tenth": Fraction(1, 10),
    "pi": PI, "pi2": PI / 2, "pi4": PI / 4, "twopi": 2 * PI,
    "invpi2": 1 / (PI / 2),
    "pi2hi": hi24(PI / 2, 17), "pi2lo": PI / 2 - hi24(PI / 2, 17),
    "ln2": LN2, "ln2hi": hi24(LN2), "ln2lo": LN2 - hi24(LN2), "invln2": 1 / LN2,
    "ln10": LN10, "invln10": 1 / LN10, "log2e": 1 / LN2,
    "e": E, "degrad": PI / 180, "raddeg": 180 / PI,
    "sqrt_half": D("0.70710678118654752440084436210484903928"),
    "p1": Fraction(10), "p2": Fraction(100), "p4": Fraction(10 ** 4), "p8": Fraction(10 ** 8), "p16": Fraction(10 ** 16), "p32": Fraction(10 ** 32),
    "e8": Fraction(10 ** 8), "e9": Fraction(10 ** 9), "tiny": Fraction(1, 10 ** 12),
    "three": Fraction(3), "four": Fraction(4), "sixty": Fraction(60), "r360": Fraction(360), "r180": Fraction(180), "r90": Fraction(90),
    "c1e10": Fraction(10 ** 10), "c1e5": Fraction(10 ** 5), "c1e4": Fraction(10 ** 4),
    "neg10": Fraction(-10), "six": Fraction(6), "neg6": Fraction(-6), "neg4": Fraction(-4), "f55": Fraction(55), "f95": Fraction(95),
    "neg2pi": -2 * PI, "h3": Fraction(1, 1000), "f20": Fraction(5, 100), "quarter": Fraction(1, 4),
}

POLYS = {"exp": coeffs_exp, "sin": coeffs_sin, "cos": coeffs_cos, "atan": coeffs_atan, "atanh": coeffs_atanh}


def write_consts(path):
    out = ["; GENERATED by tools/fxlib.py -- 6-byte float constants\n"]
    for k, v in SCALAR.items():
        out.append("fxk_%s:\n    %s\n" % (k, db(pack(v))))
    for k, f in POLYS.items():
        cs = f()
        out.append("fxp_%s:                         ; %d coefficients, highest degree first\n" % (k, len(cs)))
        for c in cs:
            out.append("    %s\n" % db(pack(c)))
    open(path, "w").write("".join(out))


TOKENS = ["sin", "cos", "tan", "asin", "acos", "atan", "sinh", "cosh", "tanh", "asinh", "acosh", "atanh", "ln", "log", "log2", "sqrt",
          "cbrt", "exp", "abs", "floor", "ceil", "int", "frac", "sign", "round", "mod", "nCr", "nPr", "min", "max", "10^"]
TOKEN_CODE = {n: 0x80 + i for i, n in enumerate(TOKENS)}


def tokenize(text):
    """friendly text ('sin(30)+2pi') -> token bytes as a latin-1 str.  pi, ans, e (alone) and E (EE key) become tokens"""
    out = []
    i = 0
    names = sorted(TOKENS, key=len, reverse=True)
    while i < len(text):
        for n in names:
            if text.startswith(n + "(", i):
                out.append(chr(TOKEN_CODE[n]))
                i += len(n) + 1
                break
        else:
            if text.startswith("pi", i):
                out.append(chr(0xF0))
                i += 2
            elif text.startswith("ans", i):
                out.append(chr(0xF1))
                i += 3
            elif text[i] == "e":
                out.append(chr(0xF2))
                i += 1
            elif text[i] == "E":
                out.append(chr(0xF3))
                i += 1
            else:
                out.append(text[i])
                i += 1
    return "".join(out)


if __name__ == "__main__":
    import sys
    write_consts(sys.argv[1] if len(sys.argv) > 1 else "consts.inc")
